'use strict';
// Erkennt installierte Slicer (Version, aktiver Drucker, Benutzer-Profilordner) und
// installiert erzeugte Profile auf Wunsch direkt in deren Benutzerordner.
const fs = require('fs');
const path = require('path');

const APPDATA = process.env.APPDATA || '';

const DEFS = {
  orca: { label: 'OrcaSlicer', dir: 'OrcaSlicer', conf: 'OrcaSlicer.conf' },
  bambu: { label: 'Bambu Studio', dir: 'BambuStudio', conf: 'BambuStudio.conf' },
  snapmaker: { label: 'Snapmaker Orca', dir: 'Snapmaker_Orca', conf: 'Snapmaker_Orca.conf' },
  prusa: { label: 'PrusaSlicer', dir: 'PrusaSlicer', conf: 'PrusaSlicer.ini' },
};

function readConfJson(f) {
  try {
    const t = fs.readFileSync(f, 'utf8').split(/\r?\n/).filter(l => !l.startsWith('#')).join('\n');
    return JSON.parse(t);
  } catch { return null; }
}

function profileVersionToTag(v) {
  const m = String(v || '').match(/^(\d+)\.(\d+)\.(\d+)/);
  return m ? `v${+m[1]}.${+m[2]}.${+m[3]}` : null;
}

function backupVersion(base) {
  let best = null;
  for (const d of fs.readdirSync(base)) {
    const m = d.match(/^user_backup-v(\d+(?:\.\d+)*)$/);
    if (m && (!best || m[1].localeCompare(best, undefined, { numeric: true }) > 0)) best = m[1];
  }
  return best;
}

function userFilamentDir(base) {
  const u = path.join(base, 'user');
  if (!fs.existsSync(u)) return path.join(u, 'default', 'filament');
  let best = null, bestT = -1;
  for (const d of fs.readdirSync(u)) {
    const f = path.join(u, d, 'filament');
    if (!fs.existsSync(f)) continue;
    const t = fs.statSync(f).mtimeMs;
    if (t > bestT) { bestT = t; best = f; }
  }
  return best || path.join(u, 'default', 'filament');
}

function systemPresetNames(base) {
  const names = new Set();
  const sys = path.join(base, 'system');
  if (!fs.existsSync(sys)) return names;
  for (const vendor of fs.readdirSync(sys)) {
    const fd = path.join(sys, vendor, 'filament');
    if (!fs.existsSync(fd)) continue;
    (function walk(d) {
      for (const e of fs.readdirSync(d, { withFileTypes: true })) {
        if (e.isDirectory()) walk(path.join(d, e.name));
        else if (e.name.endsWith('.json')) names.add(e.name.slice(0, -5));
      }
    })(fd);
  }
  return names;
}

function detect() {
  const out = {};
  for (const [id, d] of Object.entries(DEFS)) {
    const base = path.join(APPDATA, d.dir);
    if (!fs.existsSync(base)) continue;
    const info = { id, label: d.label, base };
    if (id === 'orca') {
      const lib = readConfJson(path.join(base, 'system', 'OrcaFilamentLibrary.json'));
      info.version = lib && lib.version;
      info.tag = profileVersionToTag(info.version);
      const conf = readConfJson(path.join(base, d.conf));
      info.activePrinter = conf && conf.presets && conf.presets.machine;
      info.userDir = userFilamentDir(base);
      info.systemNames = systemPresetNames(base);
    } else if (id === 'snapmaker') {
      // Die App-Version steht nicht in der Konfig; Orca-Forks legen beim Versionswechsel user_backup-v<Version> an.
      info.version = backupVersion(base);
      info.tag = info.version ? 'v' + info.version : null;
      const conf = readConfJson(path.join(base, d.conf));
      info.activePrinter = conf && conf.presets && conf.presets.machine;
      info.userDir = userFilamentDir(base);
      info.systemNames = systemPresetNames(base);
    } else if (id === 'bambu') {
      const conf = readConfJson(path.join(base, d.conf));
      info.version = conf && conf.app && conf.app.version;
      info.tag = info.version ? 'v' + info.version : null;
      info.activePrinter = conf && conf.presets && conf.presets.machine;
      info.userDir = userFilamentDir(base);
      info.systemNames = systemPresetNames(base);
    } else if (id === 'prusa') {
      info.userDir = path.join(base, 'filament');
      try {
        const ini = fs.readFileSync(path.join(base, d.conf), 'utf8');
        const m = ini.match(/^# generated by PrusaSlicer ([\d.]+)/m);
        if (m) { info.version = m[1]; info.tag = 'version_' + m[1]; }
      } catch { /* ignore */ }
    }
    out[id] = info;
  }
  // Cura: %APPDATA%\cura\<version>\materials
  const curaBase = path.join(APPDATA, 'cura');
  if (fs.existsSync(curaBase)) {
    const vers = fs.readdirSync(curaBase).filter(v => /^\d+\.\d+/.test(v)).sort((a, b) => parseFloat(b) - parseFloat(a));
    if (vers.length) out.cura = { id: 'cura', label: 'UltiMaker Cura', base: path.join(curaBase, vers[0]), version: vers[0], userDir: path.join(curaBase, vers[0], 'materials') };
  }
  return out;
}

function publicInfo(local) {
  const o = {};
  for (const [k, v] of Object.entries(local)) {
    o[k] = { label: v.label, version: v.version, tag: v.tag, activePrinter: v.activePrinter, userDir: v.userDir, systemPresets: v.systemNames ? v.systemNames.size : undefined };
  }
  return o;
}

// Schreibt Dateien in den Benutzerordner des Slicers. Überschreibt nur mit overwrite=true.
// Orca/Bambu legen eigenständige Profile (ohne „inherits“) im Unterordner „base“ ab.
function install(local, slicer, files, overwrite, subdir) {
  const info = local[slicer];
  if (!info || !info.userDir) throw new Error('Slicer nicht gefunden');
  const dir = subdir ? path.join(info.userDir, subdir) : info.userDir;
  fs.mkdirSync(dir, { recursive: true });
  const written = [];
  for (const f of files) {
    if (/[\\/]/.test(f.name) || f.name.startsWith('.')) throw new Error('Ungültiger Dateiname');
    const target = path.join(dir, f.name);
    if (fs.existsSync(target) && !overwrite) {
      const e = new Error('Datei existiert bereits: ' + target);
      e.code = 'EXISTS';
      throw e;
    }
    written.push({ target, content: f.content });
  }
  for (const w of written) fs.writeFileSync(w.target, w.content, 'utf8');
  return written.map(w => w.target);
}

module.exports = { detect, publicInfo, install };
